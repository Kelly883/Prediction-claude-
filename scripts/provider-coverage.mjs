#!/usr/bin/env node
/**
 * Generates docs/PROVIDER_COVERAGE_REPORT.md.
 *
 * Single source of truth: lib/api/provider-mapping.json (internal league ->
 * provider identifier map) and lib/analysis/defaults.json (product league list).
 *
 * "Supported" here means the provider has an addressable identifier for the
 * league under the configured plan tier (API-Football numeric id; Football-Data
 * free-tier competition code). It is a static entitlement check, not a live
 * probe; run the app with real credentials for live verification.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const mappings = require(resolve(root, 'lib/api/provider-mapping.json'));
const defaults = require(resolve(root, 'lib/analysis/defaults.json'));

const productLeagues = defaults.leagues.map((l) => l.leagueCode);
const mappingByCode = new Map(mappings.map((m) => [m.code, m]));

const providers = [
  { id: 'api-football', label: 'API-Football (api-sports.io)', key: 'apiFootballId' },
  { id: 'football-data', label: 'Football-Data.org', key: 'footballDataCode' },
];

function rowsFor(key) {
  const supported = [];
  const unsupported = [];
  for (const code of productLeagues) {
    const mapping = mappingByCode.get(code);
    const value = mapping ? mapping[key] : undefined;
    if (value !== undefined && value !== null) supported.push({ code, value, name: mapping.name });
    else unsupported.push({ code, name: mapping ? mapping.name : code });
  }
  return { supported, unsupported };
}

const generatedAt = new Date().toISOString();

let md = '';
md += '# Provider Coverage Report\n\n';
md += `Generated: ${generatedAt}\n\n`;
md += 'This report is generated by `scripts/provider-coverage.mjs` from the authoritative\n';
md += 'internal league map (`lib/api/provider-mapping.json`). "Supported" means the provider\n';
md += 'has an addressable identifier for the league under the configured plan tier. It is a\n';
md += 'static entitlement check, not a live API probe.\n\n';
md += `Product league count: **${productLeagues.length}**\n\n`;

for (const provider of providers) {
  const { supported, unsupported } = rowsFor(provider.key);
  md += `## ${provider.label}\n\n`;
  md += `Supported: **${supported.length}/${productLeagues.length}**\n\n`;
  md += '| Internal code | Provider identifier | League |\n';
  md += '|---|---|---|\n';
  for (const row of supported) md += `| ${row.code} | ${row.value} | ${row.name} |\n`;
  md += '\n';
  md += `Not covered by this provider (${unsupported.length}): ${unsupported.map((u) => u.code).join(', ') || '—'}\n\n`;
}

md += '## Documented plan limits\n\n';
md += '| Provider | Plan | Requests | Coverage | Source |\n';
md += '|---|---|---|---|---|\n';
md += '| API-Football | Free (default) | 100 requests/day | All leagues technically addressable; season entitlement limited to recent seasons (approx. Year-4..Year-2) | api-sports.io pricing/docs |\n';
md += '| Football-Data.org | Free (Tier One) | 10 requests/minute | 12 competitions only (PL, ELC, BL1, DED, BSA, PD, FL1, SA, PPL, CL, EC, WC) | football-data.org docs |\n\n';

md += '## Conclusion\n\n';
md += '- Every product league has an addressable API-Football id, but the **free tier (100 requests/day,\n';
md += '  season-restricted) cannot serve 20 leagues plus per-fixture enrichment**. Enrichment alone issues\n';
md += '  multiple calls per fixture, so a 20-league daily run will exhaust the free quota.\n';
md += '- Football-Data.org free tier covers only **10 of the 20** product leagues (PL, PD, BL1, SA, FL1,\n';
md += '  PPL, ERE→DED, CL, ELC, BRA→BSA). It cannot serve EL, ECL, BL2, PD2, SA2, FL2, MLS, LIB, J1, ARG.\n';
md += '- Therefore, **the free tiers cannot support verified 20-league coverage**. See the remediation\n';
md += '  report for the exact alternatives (paid provider tiers) and their trade-offs.\n';

const outDir = resolve(root, 'docs');
mkdirSync(outDir, { recursive: true });
const outPath = resolve(outDir, 'PROVIDER_COVERAGE_REPORT.md');
writeFileSync(outPath, md, 'utf8');

console.log(`Provider coverage report written to ${outPath}`);
for (const provider of providers) {
  const { supported, unsupported } = rowsFor(provider.key);
  console.log(`- ${provider.label}: ${supported.length}/${productLeagues.length} supported; missing ${unsupported.map((u) => u.code).join(', ') || 'none'}`);
}
